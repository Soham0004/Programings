<?php
#String Operations

//Get length of the string
    echo strlen("Hello World!");
    echo "<br>";

//Number  of words in the string
    echo str_word_count("Welcome to PHP class");
    echo "<br>";

//Reverse a string
    echo strrev("Hello World!");
    echo "<br>";

//Find the position of the specified string
    echo strpos("Hello world!", "world");
    echo "<br>";

//Replace a string
    echo str_replace("world", "Disney", "Hello world!");
    echo "<br>";
?>